import * as React from 'react';
import { Icon } from '@/components/icons/icons';
import { cn } from '@/lib/cn';

export interface AiChipProps extends React.HTMLAttributes<HTMLSpanElement> {
  label?: string;
  size?: 'sm' | 'default';
}

export function AiChip({ label = 'AI', size = 'default', className, ...props }: AiChipProps) {
  return (
    <span
      className={cn(
        'rounded-chip bg-violet-soft text-violet-ink inline-flex shrink-0 items-center gap-1 font-medium select-none',
        size === 'sm' ? 'px-1.5 py-0.5 text-[10px]' : 'px-2 py-0.5 text-xs',
        className,
      )}
      title="Generated by AI"
      {...props}
    >
      <Icon name="sparkle" size={16} />
      <span>{label}</span>
    </span>
  );
}
